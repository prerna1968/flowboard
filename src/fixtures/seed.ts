function statusesFor(listId: string): Status[] {
  return [
    { id: `${listId}-todo`, listId, name: "To do", category: "todo", color: "todo", position: 0 },
    {
      id: `${listId}-in_progress`,
      listId,
      name: "In progress",
      category: "in_progress",
      color: "in_progress",
      position: 1,
    },
    { id: `${listId}-done`, listId, name: "Done", category: "done", color: "done", position: 2 },
  ];
}

function task(
  input: Pick<Task, "id" | "title" | "primaryListId" | "statusId" | "position"> & Partial<Task>,
): Task {
  return {
    description: "",
    priority: "none",
    assigneeIds: [],
    dueDate: null,
    parentTaskId: null,
    createdAt,
    updatedAt,
    archivedAt: null,
    ...input,
  };
}

